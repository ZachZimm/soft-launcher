import { writeFile } from 'node:fs/promises';
import { SoftIf, Policy, ollama } from 'soft-if';
import { buildQuestions } from '../src/lib/loop';
import { buildState } from '../src/lib/state';
import { catalogueFixture, syntheticState } from '../bench/fixtures';
const path = new URL('./decision-probe-payload.json', import.meta.url);
const state = syntheticState(await catalogueFixture());
const payload = JSON.stringify({ state: buildState('2+2', state).serialized, questions: buildQuestions(state.catalogue.actions), model: (process.env.SOFT_LAUNCHER_CLEF_MODEL ?? 'clef-flash-q8:latest') });
await writeFile(path, payload);
const started = performance.now();
const res = await fetch('http://127.0.0.1:11434/v1/systemone', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: payload, signal: AbortSignal.timeout(60_000) });
const headersMs = Math.round(performance.now() - started);
const body = await res.json() as any;
const raw = { status: res.status, headersMs, bodyMs: Math.round(performance.now() - started), answerKeys: Object.keys(body.answers ?? {}), leader: body.answers?.action?.choice, usage: body.usage };
const soft = new SoftIf({ backend: ollama({ url: 'http://127.0.0.1:11434', model: (process.env.SOFT_LAUNCHER_CLEF_MODEL ?? 'clef-flash-q8:latest') }), policy: new Policy(), defaultTimeoutMs: 1500 });
const parsed = JSON.parse(payload);
const decision = await soft.decide(parsed.state, parsed.questions);
await soft.close();
const softResult = { error: decision.error, leader: decision.action.choice, latencyMs: decision.latency_ms, usage: decision.usage };
console.log(JSON.stringify({ raw, soft: softResult }));
await writeFile(new URL('./decision-probe-node.json', import.meta.url), JSON.stringify({ raw, soft: softResult }, null, 2));
